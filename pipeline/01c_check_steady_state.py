def main():
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument('--params-dir', default='outputs/elevts',
                   help='Directory containing params-{job_id}.pkl files. '
                        'Default: outputs/elevts.')
    p.add_argument('--job-ids', nargs='+', default=None,
                   help='Restrict to these job IDs. Default: all found.')
    p.add_argument('--series', default='ts_mean_elevs',
                   choices=['ts_mean_elevs', 'ts_max_elevs'],
                   help='Series to characterize. ts_max_elevs is the relief '
                        'proxy and the stricter test. Default: ts_mean_elevs.')
    p.add_argument('--reference', default='final',
                   choices=['final', 'window-mean'],
                   help="Level the deviation is measured against. 'final' is "
                        'z(t*=1), the snapshot feature extraction uses. '
                        "Default: final.")
    p.add_argument('--norm-window', type=int, default=None,
                   help='Trailing points averaged when --reference '
                        'window-mean. Defaults to --fit-window, so that the '
                        'reference is the centre of the interval being '
                        'tested; any other value references the window to a '
                        'point partway inside it.')
    p.add_argument('--fit-window', type=int, default=5,
                   help='Trailing points forming the final window, over '
                        'which the range, dz_max and mono are evaluated. '
                        'Default: 5.')
    p.add_argument('--delta', type=float, default=1e-3,
                   help='Containment level for the verified flag, the '
                        'summary and the figure guide line. Default: 1e-3.')
    p.add_argument('--mono-flag', type=float, default=0.9,
                   help='Monotonicity ratio below which a tail is flagged as '
                        'reversing within the window. Default: 0.9.')
    p.add_argument('--draw-curves', dest='draw_curves', action='store_true',
                   default=None,
                   help=f'Draw individual rasterized curves instead of '
                        f'quantile bands. Default: curves below '
                        f'{BAND_MIN_N} landscapes, bands at or above.')
    p.add_argument('--no-draw-curves', dest='draw_curves',
                   action='store_false',
                   help='Force quantile bands regardless of ensemble size.')
    p.add_argument('--no-plot', dest='plot', action='store_false',
                   help='Write the CSV only, suppressing both figures.')
    p.add_argument('--no-space-plot', dest='space_plot', action='store_false',
                   help='Skip the (U/Ks, Kh/Ks) coverage figure.')
    p.add_argument('--point-size', type=float, default=11.0,
                   help='Marker area in the coverage figure. Default: 11.')
    p.add_argument('--no-manifest', dest='manifest', action='store_false',
                   help='Skip the -excluded.csv manifest of failed landscapes.')
    p.add_argument('--formats', nargs='+', default=['png'],
                   help='Figure formats to write. Default: png.')
    p.add_argument('--out-dir', default='.',
                   help='Directory for the derived output filenames.')
    p.add_argument('--out-stem', default=None,
                   help='Override the derived filename stem.')
    args = p.parse_args()

    if args.norm_window is None:
        args.norm_window = args.fit_window
    if args.fit_window < 3:
        sys.exit("ERROR: --fit-window must be at least 3 to give a "
                 "meaningful tail window.")

    df = load_params(args.params_dir, args.job_ids)
    if args.series not in df.columns:
        sys.exit(f"ERROR: column '{args.series}' not in the parameter table; "
                 f"got {list(df.columns)}.")

    res, curves = check_ensemble(df, args.series, args.reference,
                                 args.norm_window, args.fit_window,
                                 args.delta)

    git_hash = _git_hash()
    csv_path = derive_out_path(args, git_hash, 'csv')
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    res.to_csv(csv_path, index=False)

    print_summary(res, curves, args)
    print(f"\nWrote {csv_path}")

    if args.manifest:
        man = res.loc[~res['verified'],
                      ['job_id', 'landscape_idx', 'exclusion_reason',
                       'range_rel', 'dz_max', 'mono']]
        man_path = csv_path.with_name(csv_path.stem + '-excluded.csv')
        man.to_csv(man_path, index=False)
        print(f"Wrote {man_path}  ({len(man):,} excluded, "
              f"{int(res['verified'].sum()):,} retained)")

    if args.plot and curves is not None:
        fig = make_figure(res, curves, args)
        for ext in args.formats:
            fig_path = derive_out_path(args, git_hash, ext)
            fig.savefig(fig_path, bbox_inches='tight', facecolor='white')
            print(f"Wrote {fig_path}")
    elif args.plot:
        print("No testable landscapes; figure skipped.")

    if args.plot and args.space_plot:
        fig = make_space_figure(res, args.point_size)
        if fig is None:
            print("Parameter columns absent; space figure skipped.")
        else:
            for ext in args.formats:
                base = derive_out_path(args, git_hash, ext)
                sp = base.with_name(base.stem + '-space' + base.suffix)
                fig.savefig(sp, bbox_inches='tight', facecolor='white')
                print(f"Wrote {sp}")


if __name__ == '__main__':
    main()
