"""
01c_check_steady_state.py
=========================
Per-landscape verification of topographic steady state for the landscapes
generated by ``01_generate_landscapes.py``.

Each row of ``params-{job_id}.pkl`` carries ``ts_mean_elevs`` and
``ts_max_elevs``, the mean and maximum elevation of the core nodes at every one
of the NUM_TS (100) time steps of that landscape's run.  The final time step is
the landscape that feature extraction operates on.

A two-step determination
------------------------
A single model time T_ss = T_TC / Ks with T_TC = 25 is estimated from a small
experiment and applied to the whole ensemble, fixing the length of every
production run.  That is a screening estimate and cannot be more: it comes
from a subsample, whereas the time a landscape needs to equilibrate depends on
its own parameters.  Whether any individual landscape actually reached steady
state within it is settled here, per landscape, from the elevation record of
its own run.  This script is the second step.

Landscapes that fail verification are excluded from the study population and
listed in a manifest beside the main table.  That exclusion is not uniform
over the parameter space -- empirically it concentrates at high Kh/Ks -- so
the second figure maps where it falls, and the coverage it leaves must be
reported rather than assumed.

Everything here is computed from the stored time series alone.  No LE
parameter, no T_ss and no elev_err enters the criterion: steady state is a
property of the stage-01 model run, and must not be licensed by a downstream
observational choice made at stage 02.  LE parameters are carried through to
the output only so the results can be grouped afterwards.

The conventional criterion and its limitations
----------------------------------------------
The conventional test of steady state applies a threshold to the change in
elevation between successive time steps, |Z(t) - Z(t-1)| < epsilon.  Two
limitations of that form are well recognized and generally accepted.

First, epsilon carries units of length.  It scales with the time step, so
halving dt halves the measured change with no change in the physics, and it
scales with the characteristic height hc = U/Ks, so at a fixed degree of
convergence a landscape with large U/Ks produces a much larger per-step change
in metres.  Across an ensemble spanning orders of magnitude in dt and in U/Ks,
one epsilon is a far stricter standard at one end than the other.

Second, a per-step threshold bounds the rate of change but not the change
accumulated over many steps: a landscape can satisfy it at every step while
drifting steadily.

Adoption in normalized time and elevation
-----------------------------------------
1.  Scale.  Divide the series by its final value.  Elevation is then a
    fraction of each landscape's own final mean elevation and the normalized
    time step dt/T_ss = 1/NUM_TS is identical for every run, so one tolerance
    means the same thing for every landscape.  This addresses the first
    limitation.  Note the scaling fixes a unit only: the measure in step 2 is
    a range, which has no zero point and so does not depend on which value is
    chosen here.  ``--reference`` selects it for comparison.

2.  Range over the final window.  The hypothesis verified for each landscape
    is that the final window of its series is at steady state.  A single time
    step carries no evidence of its own stationarity, so the object of the
    test is an interval and the evidence is how much the series varies across
    it.  Under this hypothesis every step within the window is an equally
    admissible representative, and the use of the final step for feature
    extraction is a convention rather than a privileged choice.  Define

        R(t*) = max over tau >= t* of z*(tau)
                - min over tau >= t* of z*(tau)

    which is non-increasing by construction, since extending the interval
    backwards can only widen the range.  ``range_rel`` is R at the start of
    the final window and is the criterion.  R is a range in elevation over an
    interval in time; the interval is the window, the range is what is
    measured across it.

    R is the accumulated form of the conventional quantity, which addresses
    the second limitation: over a one-directional window R is the sum of the
    per-step changes rather than the largest of them, so bounding R bounds the
    drift accumulated across the window.

    The premise is that the latter part of the series already represents
    steady state; the window is an arbitrary selection from within that part,
    made to test the premise quantitatively rather than to locate where steady
    state begins.  Its length is a choice, as ``--delta`` is, and the two act
    in the same direction: because R is non-increasing in t*, a longer window
    or a smaller delta both tighten the criterion.

    The settling time is the point from which the range stays below a given
    level,

        Ts(delta) = first t* at which R(t*) <= delta

    and because R is monotone the first and last such t* coincide, so no
    first-versus-last rule is needed.  A deviation measured from a fixed
    reference would need one, since these landscapes overshoot their final
    value (by ~2% near t* = 0.3) and so pass through it on the way up.  For
    the same reason a "fraction of total change completed" measure is not
    used: with an overshoot it is not monotone in t* and its interpretation
    fails.

3.  Reported alongside, as plain differences of the series, with no model
    fitted and no statistical test applied:

    ``dz_max``   the largest per-step change over the window, so a reader may
                 apply the conventional criterion directly to these results.
    ``mono``     R divided by the total variation over the window: 1 where the
                 window varies in a single direction, below 1 where it
                 reverses.

4.  Verify.  ``--delta`` sets the range below which a window is verified.  The
    output carries the full distribution of R, Ts, dz_max and mono, so a
    reader can apply any level they like.

        verified      range_rel < delta
        not verified  range at or above delta, or series untestable

    What this establishes is that the mean elevation varies by less than delta
    across the final window, and it bounds the per-step rate within it.  It
    does not bound the distance between the analyzed landscape and its
    asymptotic state: a window can be narrow while still drifting slowly, so
    its own values need not bracket the asymptote, and the remaining approach
    cannot be estimated reliably from a trajectory of this length.

Usage
-----
    python 01c_check_steady_state.py --params-dir outputs/elevts \
        --out-dir outputs/steady-state

    python 01c_check_steady_state.py --params-dir outputs/elevts \
        --series ts_max_elevs --out-dir outputs/steady-state

    python 01c_check_steady_state.py --params-dir outputs/elevts \
        --fit-window 10 --draw-curves --out-dir outputs/steady-state

Output
------
    steady-state-{series}-f{fit}-{reference}-{hash}.csv
        One row per landscape: remaining range, settling times, per-step rate,
        monotonicity, overshoot, and ``verified``.  No fitted slope, p-value
        or significance flag is written: the method uses differences of the
        recorded series only.

    steady-state-{series}-f{fit}-{reference}-{hash}-excluded.csv
        The landscapes that failed verification, with the reason, for joining
        into downstream training by (job_id, landscape_idx).  Written unless
        ``--no-manifest``.

    steady-state-{series}-f{fit}-{reference}-{hash}.png
        Panel a, normalized trajectories; panel b, R(t*).  Both as quantile
        envelopes, with the evaluated interval shaded in each.

    steady-state-{series}-f{fit}-{reference}-{hash}-space.png
        The verification outcome across the (U/Ks, Kh/Ks) plane, with the full
        ensemble shown so that the retained coverage is visible.  Suppressed
        by ``--no-space-plot``.

    The filenames encode the series, window, reference and git hash so runs
    under different settings coexist in one directory.

Notes
-----
Rows whose series is None are reported with status ``missing`` rather than
skipped silently.  ``01_generate_landscapes.py`` writes ``params-{job_id}.pkl``
once before evolving anything and rewrites it after each landscape, so a job
that died mid-run leaves a readable parameter file whose unevolved rows hold
None.  Those rows have no elevation grid on disk either and must not be
counted as either steady or non-steady.

Landscape identity is taken from ``job_id`` and ``landscape_idx`` where
present, falling back to the development-era ``tmux-sess`` and ``df-ind``
(``tmux-sess`` == ``job_id``).  Renaming happens per file, before
concatenation, so an ensemble mixing both conventions is handled.

Mean elevation is the integral measure; maximum elevation is the relief proxy
(base level is zero along the open boundaries) and is the stricter of the two,
since the divide region equilibrates last.  Run both.

Dependencies
------------
    numpy, pandas, matplotlib
    See environment.yml for pinned versions.
"""

