def normalize_keys(df: pd.DataFrame, path: str) -> pd.DataFrame:
    """Rename a single file's identifier columns to the canonical pair.

    Parameters
    ----------
    df : pd.DataFrame
        One parameter table as read from disk.
    path : str
        Source path, for messages.

    Returns
    -------
    pd.DataFrame
        Frame carrying ``job_id`` and ``landscape_idx``.

    Raises
    ------
    SystemExit
        If no candidate identifier pair is present, since without an
        identifier the output rows cannot be joined back to features or
        elevation grids.

    Notes
    -----
    Renaming happens per file rather than after concatenation: an ensemble
    assembled over time can mix development-era files keyed on
    ``('tmux-sess', 'df-ind')`` with later files keyed on
    ``('job_id', 'landscape_idx')``, and concatenating those first would
    produce four identifier columns half-filled with NaN.
    """
    canonical = KEY_CANDIDATES[0]
    for pair in KEY_CANDIDATES:
        if all(c in df.columns for c in pair):
            if pair == canonical:
                return df
            print(f"  {os.path.basename(path)}: legacy identifier columns "
                  f"{pair} renamed to {canonical}.")
            return df.rename(columns=dict(zip(pair, canonical)))
    sys.exit(
        f"ERROR: no landscape identifier found in {path}. Expected one of "
        f"{KEY_CANDIDATES}; got columns {list(df.columns)}."
    )


def load_params(params_dir: str, job_ids: list = None) -> pd.DataFrame:
    """Load and concatenate ``params-{job_id}.pkl`` files.

    Parameters
    ----------
    params_dir : str
        Directory containing parameter DataFrames written by
        ``01_generate_landscapes.py``.
    job_ids : list of int or str, optional
        If given, load only these job IDs. Otherwise every file matching
        ``params-*.pkl`` in ``params_dir`` is loaded.

    Returns
    -------
    pd.DataFrame
        Concatenated DataFrame, one row per landscape, keys normalized.

    Raises
    ------
    FileNotFoundError
        If specific job IDs are requested but their files are missing, or if
        no matching files are found.
    """
    if job_ids:
        paths = [os.path.join(params_dir, f'params-{jid}.pkl')
                 for jid in sorted(job_ids)]
        missing = [p for p in paths if not os.path.exists(p)]
        if missing:
            raise FileNotFoundError(f"Parameter files not found: {missing}")
    else:
        pattern = os.path.join(params_dir, 'params-*.pkl')
        paths = sorted(glob.glob(pattern))
        if not paths:
            raise FileNotFoundError(
                f"No parameter files found matching '{pattern}'"
            )

    dfs = [normalize_keys(pd.read_pickle(p), p) for p in paths]
    df = pd.concat(dfs, ignore_index=True)
    print(f"Loaded {len(df):,} landscapes from {len(paths)} file(s).")
    return df


