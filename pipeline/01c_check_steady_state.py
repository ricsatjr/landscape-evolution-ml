def derive_out_path(args, git_hash: str, ext: str) -> Path:
    """Build an output path from the CLI arguments.

    Parameters
    ----------
    args : argparse.Namespace
    git_hash : str
        Short commit hash, or 'unknown'.
    ext : str
        File extension without the dot.

    Returns
    -------
    Path

    Notes
    -----
    ``--out-stem`` overrides the derived stem. Otherwise the name encodes the
    series, window and reference so that runs under different settings coexist
    in one directory rather than overwriting one another.
    """
    stem = args.out_stem or (
        f"steady-state-{args.series.replace('ts_', '').replace('_elevs', '')}"
        f"-f{args.fit_window}-{args.reference}-{git_hash}"
    )
    return Path(args.out_dir) / f'{stem}.{ext}'


def print_summary(res: pd.DataFrame, curves: dict, args, levels=LEVELS):
    """Print the distribution of the remaining-range statistics.

    Parameters
    ----------
    res : pd.DataFrame
    curves : dict or None
    args : argparse.Namespace
    levels : sequence of float

    Notes
    -----
    Ensemble settling times are read from the pointwise maximum of G, so they
    are statements about every landscape simultaneously rather than about a
    median or a quantile.
    """
    counts = res['status'].value_counts()
    ok = res[res['status'] == 'ok']
    print(f"\nSeries: {args.series} | reference: {args.reference} | "
          f"fit window: {args.fit_window} | delta: {args.delta:g}")
    print(f"Landscapes: {len(res):,}  "
          + "  ".join(f"{k}={v:,}" for k, v in counts.items()))
    if not len(ok):
        return

    print(f"\nOvershoot above the reference level: "
          f"median {100 * ok['overshoot'].median():.2f}%  "
          f"max {100 * ok['overshoot'].max():.2f}%  "
          f"at t* {ok['t_peak'].min():.2f}-{ok['t_peak'].max():.2f}")

    q = ok['range_rel'].quantile([0.5, 0.95, 0.99, 1.0])
    print(f"\nRange of z* over the final {args.fit_window} points "
          f"(t* >= {ok['t_fit'].iloc[0]:.2f}):")
    for lab, v in q.items():
        print(f"  {lab:>5.2f}  {v:.3e}")

    print("\nSettling time Ts(delta) -- t* from which the range stays "
          "below delta:")
    print(f"  {'delta':>8} {'median':>8} {'max':>8} {'never':>7}")
    for lv in levels:
        col = ok[f'Ts_{lv:g}']
        print(f"  {lv:>8.0e} {col.median():>8.2f} {col.max():>8.2f} "
              f"{int(col.isna().sum()):>7d}")
    if curves is not None:
        R = curves['R'][:, :-1]
        n = curves['R'].shape[1]

        def _cross(rr):
            return "  ".join(
                f"{lv:g}@{(np.flatnonzero(rr <= lv)[0] + 1) / n:.2f}"
                if len(np.flatnonzero(rr <= lv)) else f"{lv:g}@-"
                for lv in levels)

        print("  max over all landscapes crosses:      " + _cross(R.max(axis=0)))
        vmask = ok['verified'].to_numpy(bool)
        if vmask.any():
            print("  max over verified landscapes crosses: "
                  + _cross(R[vmask].max(axis=0)))

    print(f"\nPer-step change over the final {args.fit_window} points "
          f"(the conventional measure, normalized units):")
    print(f"  dz_max median {ok['dz_max'].median():.3e}  "
          f"p95 {ok['dz_max'].quantile(0.95):.3e}  "
          f"max {ok['dz_max'].max():.3e}")
    print(f"  monotonicity ratio: median {ok['mono'].median():.3f}  "
          f"below {args.mono_flag:g} in {int((ok['mono'] < args.mono_flag).sum()):,} "
          f"({100 * (ok['mono'] < args.mono_flag).mean():.1f}%)")
    ep = ok['end_pos']
    print(f"  final value is an endpoint of its window in "
          f"{int(((ep < 0.01) | (ep > 0.99)).sum()):,} of {len(ok):,}")

    nv = int(ok['verified'].sum())
    print(f"\nVerification at delta={args.delta:g} "
          f"(the range over the final window is below delta; this bounds "
          f"the variation across the window, not the distance to the "
          f"asymptotic state):")
    print(f"  verified (range < delta)  {nv:>6,}  "
          f"({100 * nv / len(ok):5.1f}%)")
    print(f"  not verified              {len(ok) - nv:>6,}  "
          f"({100 * (len(ok) - nv) / len(ok):5.1f}%)")

    if (~ok['verified']).any() and 'kh_ks' in ok.columns:
        exc = ok[~ok['verified']]
        print("\nCoverage of the exclusions:")
        print(f"  Kh/Ks  {exc['kh_ks'].min():.2e}-{exc['kh_ks'].max():.2e}  "
              f"(median {exc['kh_ks'].median():.2e})")
        for v in ('u_ks', 'kh_ks'):
            if v not in ok.columns:
                continue
            q = pd.qcut(ok[v], 5, duplicates='drop')
            rate = ok.groupby(q, observed=True)['verified'].apply(
                lambda t: 100 * (~t).mean())
            cnt = ok.groupby(q, observed=True)['verified'].apply(
                lambda t: int((~t).sum()))
            print(f"  by {v:>5s} quintile:  "
                  + "  ".join(f"{r:.1f}% ({c})"
                              for r, c in zip(rate.values, cnt.values)))

    worst = ok.nlargest(min(10, len(ok)), 'range_rel')
    cols = ['job_id', 'landscape_idx', 'range_rel', 'dz_max', 'mono',
            'end_pos', 'verified']
    print("\nLargest remaining ranges:")
    print(worst[cols].to_string(
        index=False, float_format=lambda v: f'{v: .3e}',
        formatters={'job_id': '{:d}'.format,
                    'landscape_idx': '{:d}'.format}))


