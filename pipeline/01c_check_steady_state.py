def _style():
    """Apply figure rcParams. Imported lazily so --no-plot needs no GUI."""
    import matplotlib as mpl
    mpl.rcParams.update({
        'font.family': 'DejaVu Sans', 'font.size': 8,
        'axes.edgecolor': INK2, 'axes.labelcolor': INK, 'axes.linewidth': 0.6,
        'axes.titlesize': 8.5, 'axes.titleweight': 'bold',
        'axes.titlelocation': 'left', 'xtick.color': INK2, 'ytick.color': INK2,
        'xtick.labelsize': 7.5, 'ytick.labelsize': 7.5, 'legend.frameon': False,
        'legend.fontsize': 7, 'figure.dpi': 200, 'savefig.dpi': 300,
    })


def _ensemble(ax, x, Y, draw_curves, color=C_ENS):
    """Draw an ensemble of curves as quantile bands or as individual lines.

    Parameters
    ----------
    ax : matplotlib.axes.Axes
    x : np.ndarray, shape (n,)
    Y : np.ndarray, shape (m, n)
    draw_curves : bool
        True draws m rasterized lines; False draws median and quantile bands.
    color : str
    """
    if draw_curves:
        ax.plot(x, Y.T, color=color, lw=0.5,
                alpha=max(0.012, min(0.35, 30.0 / len(Y))),
                zorder=2, rasterized=True)
        return
    for lo, hi, al in BAND_QUANTILES:
        ax.fill_between(x, np.percentile(Y, lo, axis=0),
                        np.percentile(Y, hi, axis=0),
                        color=color, alpha=al, lw=0, zorder=2)
    ax.plot(x, np.median(Y, axis=0), color=color, lw=1.3, zorder=3)


def make_figure(res: pd.DataFrame, curves: dict, args, levels=LEVELS):
    """Build the two-panel steady-state figure.

    Parameters
    ----------
    res : pd.DataFrame
        Per-landscape results from ``check_ensemble``.
    curves : dict
        Stacked ``zn`` and ``R`` arrays for the testable landscapes.
    args : argparse.Namespace
    levels : sequence of float
        Ranges drawn as guide lines in panel b.

    Returns
    -------
    matplotlib.figure.Figure

    Notes
    -----
    Both panels show the whole ensemble as quantile bands, and both mark the
    evaluated interval with the same shaded rectangle, so the two can be read
    against each other without a separate explanation in either.

    Panel b is purely distributional: quantile envelopes only, with guide
    lines at the levels of interest. Counts and settling times are printed by
    the summary and belong in the accompanying text rather than on the axes.

    R reaches zero at the final point, where the interval contains one value,
    so that point is dropped from the log axis; the axis is floored at
    Y_FLOOR for the same reason.
    """
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch, Rectangle
    from matplotlib.lines import Line2D
    _style()

    ok = res[res['status'] == 'ok'].reset_index(drop=True)
    Z, R = curves['zn'], curves['R']
    m, n = Z.shape
    t = (np.arange(n) + 1) / n
    t0 = float(ok['t_fit'].iloc[0])
    draw = args.draw_curves if args.draw_curves is not None else (m < BAND_MIN_N)
    guides = [lv for lv in levels if lv >= 3e-4]

    fig, (ax_a, ax_b) = plt.subplots(1, 2, figsize=(7.4, 3.3))
    for ax in (ax_a, ax_b):
        ax.grid(True, color=GRID, lw=0.4, zorder=0)
        ax.set_axisbelow(True)
        for sp in ('top', 'right'):
            ax.spines[sp].set_visible(False)
        ax.set_xlim(0, 1.0)
        ax.set_xlabel('normalized time  $t^* = t/T_{ss}$')

    def _window(ax):
        """Shade the interval over which the criterion is evaluated."""
        ax.add_patch(Rectangle((t0, 0), 1.0 - t0, 1, transform=ax.get_xaxis_transform(),
                               facecolor=C_WIN, edgecolor='none', zorder=1))

    # ---- (a) normalized trajectories --------------------------------------
    _window(ax_a)
    _ensemble(ax_a, t, Z, draw)
    ax_a.axhline(1.0, color=INK2, lw=0.6, ls=(0, (4, 3)), zorder=4)
    ax_a.set_ylabel('$z^* = \\bar z / \\bar z(t^*{=}1)$')
    ax_a.set_title('a   Normalized mean-elevation trajectories')
    band_handles = ([Line2D([], [], color=C_ENS, lw=1.3, label='median'),
                     Patch(facecolor=C_ENS, alpha=0.30, label='5\u201395%'),
                     Patch(facecolor=C_ENS, alpha=0.16, label='1\u201399%')]
                    if not draw else
                    [Line2D([], [], color=C_ENS, lw=0.8, alpha=0.5,
                            label=f'{m:,} landscapes')])
    ax_a.legend(handles=band_handles
                + [Patch(facecolor=C_WIN, label=f'evaluated, $t^*\\geq${t0:.2f}')],
                loc='lower right', handlelength=1.6, handletextpad=0.5)

    # ---- (b) range remaining ----------------------------------------------
    _window(ax_b)
    Rp = np.maximum(R[:, :-1], 1e-12)
    _ensemble(ax_b, t[:-1], Rp, draw)
    for lv in guides:
        ax_b.axhline(lv, color=INK2, lw=0.55, ls=(0, (2, 2)), zorder=3)
        ax_b.text(1.005, lv, f'{100 * lv:g}%', fontsize=6.8, color=INK2,
                  va='center')
    ax_b.set_yscale('log')
    ax_b.set_ylim(Y_FLOOR, 1.5)
    ax_b.set_ylabel('$R(t^*)$   range of $z^*$ over $[t^*,\\,1]$')
    ax_b.set_title('b   Elevation range remaining after $t^*$')

    fig.suptitle(f'Steady-state verification  ·  {args.series}  ·  '
                 f'n = {m:,} landscapes',
                 fontsize=9, x=0.012, ha='left', y=1.0)
    fig.tight_layout()
    return fig


def _log_ticks(ax, which: str, lo: float, hi: float):
    """Put readable major ticks on a log axis spanning less than two decades.

    Parameters
    ----------
    ax : matplotlib.axes.Axes
    which : {'x', 'y'}
    lo, hi : float
        Data range on that axis.

    Notes
    -----
    Matplotlib's default log minor labels collide when the range is short, as
    U/Ks is here. Ticks are placed at the 1-2-3-5 points of each decade inside
    the range and minor labels are suppressed.
    """
    import math
    import matplotlib as mpl
    decades = range(math.floor(math.log10(lo)), math.ceil(math.log10(hi)) + 1)
    ticks = [mm * 10 ** k for k in decades for mm in (1, 2, 3, 5)
             if lo * 0.95 <= mm * 10 ** k <= hi * 1.05]
    axis = ax.xaxis if which == 'x' else ax.yaxis
    if len(ticks) >= 3:
        axis.set_major_locator(mpl.ticker.FixedLocator(ticks))
        axis.set_major_formatter(mpl.ticker.FuncFormatter(
            lambda v, _: f'{v:,.0f}' if v >= 1 else f'{v:g}'))
    axis.set_minor_formatter(mpl.ticker.NullFormatter())


def make_space_figure(res: pd.DataFrame, point_size: float = 11.0):
    """Map the verification outcome onto the (U/Ks, Kh/Ks) plane.

    Parameters
    ----------
    res : pd.DataFrame
        Per-landscape results from ``check_ensemble``.
    point_size : float
        Marker area for the retained points; excluded points are drawn larger.

    Returns
    -------
    matplotlib.figure.Figure or None
        None if the parameter columns needed are absent.

    Notes
    -----
    The full ensemble is plotted, not only the retained set, because the
    purpose of the figure is to show where exclusion falls. Exclusion is not
    spread uniformly over the parameter space, so removing the excluded
    landscapes takes a non-random slice with it, and any analysis using
    Kh/Ks as a target or predictor inherits a truncated sampling of that axis.
    Plotting only the survivors would hide exactly that.

    The upper edge of the populated region is the characteristic-length
    filter applied at generation, not a result; it is left unannotated
    because the bound depends on each landscape's own Ly and so is a band
    rather than a line in these coordinates.
    """
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    _style()

    need = {'u_ks', 'kh_ks'}
    d = res[res['status'] == 'ok']
    if not need <= set(d.columns) or not len(d):
        return None
    d = d.copy()
    ok = d['verified'].astype(bool).to_numpy()

    fig, ax = plt.subplots(figsize=(4.4, 3.6))
    ax.set_xscale('log')
    ax.set_yscale('log')
    ax.grid(True, color=GRID, lw=0.4, zorder=0)
    ax.set_axisbelow(True)
    for sp in ('top', 'right'):
        ax.spines[sp].set_visible(False)
    ax.set_xlabel('$U/K_s$   (m)')
    ax.set_ylabel('$K_h/K_s$   (m$^2$)')

    ax.scatter(d.loc[ok, 'u_ks'], d.loc[ok, 'kh_ks'], s=point_size,
               c=C_ENS, lw=0, alpha=0.45, zorder=2, rasterized=True)
    ax.scatter(d.loc[~ok, 'u_ks'], d.loc[~ok, 'kh_ks'], s=point_size * 2.2,
               marker='D', c=C_FAIL, ec='white', lw=0.4, zorder=5)
    ax.legend(handles=[
        Line2D([], [], marker='o', ls='none', mfc=C_ENS, mec='none', ms=4.4,
               label=f'verified, retained  ({int(ok.sum()):,})'),
        Line2D([], [], marker='D', ls='none', mfc=C_FAIL, mec='white', ms=4.6,
               label=f'not verified, excluded  ({int((~ok).sum()):,})')],
        loc='lower left', handletextpad=0.5, frameon=True, framealpha=0.88,
        edgecolor='none', facecolor='white')

    _log_ticks(ax, 'x', float(d['u_ks'].min()), float(d['u_ks'].max()))
    _log_ticks(ax, 'y', float(d['kh_ks'].min()), float(d['kh_ks'].max()))

    n_fail = int((~ok).sum())
    fig.suptitle(f'Steady state across the parameter plane  ·  '
                 f'n = {len(d):,}  ·  {n_fail:,} excluded '
                 f'({100 * n_fail / len(d):.1f}%)',
                 fontsize=9, x=0.012, ha='left', y=1.0)
    fig.tight_layout()
    return fig


